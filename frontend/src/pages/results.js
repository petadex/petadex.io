/**
 * Results Page – src/pages/results.js
 * Polls /api/search/results/{sessionId} until complete, then renders results.
 */
import React, { useState, useEffect, useRef, useCallback } from "react"
import { Link, navigate } from "gatsby"
import config from "../config"
import { addJobId } from "../utils/session"
import SearchHistory from "../components/search/SearchHistory"
import ResultsView from "../components/search/ResultsView"
import { DEFAULT_RESULT_VIEW } from "../components/search/constants"
import Container from "../components/common/Container"
import { LOADING_PROMPTS } from "../components/common/TerminalLoader"
import {
  formatSeq,
  parseCorpusTargetId,
  formatTargetIdLabel,
  sequenceHrefForTargetId,
} from "../utils/lib"

const GITHUB_REPO = "ababaian/petadex.io"

const SEARCH_STAGES = [
  { id: "submit", label: "Query submitted", pct: 10 },
  { id: "index", label: "Checking for cached result", pct: 25 },
  { id: "align", label: "Running DIAMOND search against Logan", pct: 70 },
  { id: "enrich", label: "Enriching with families", pct: 90 },
  { id: "done", label: "Results ready", pct: 100 },
]

// Cap polling at ~3 min. DIAMOND/Logan finishes in ~2 min, and the orchestrator
// now writes a failure sentinel (→ status:"failed", surfaced by the poller) within
// ~16s–10min on every real failure — so this backstop only has to catch the
// dropped-async-event case where no sentinel is ever written. 3 min is strictly
// looser than any true outcome, so false positives are near-zero.
const POLL_TIMEOUT_SECONDS = 3 * 60

function buildBugReportUrl(message, jobId) {
  const title = encodeURIComponent(`[Bug] Search error: ${message}`)
  const body = encodeURIComponent(
    `## Automatic error report\n\n**Job ID:** \`${jobId || "N/A"}\`\n` +
      `**URL:** ${
        typeof window !== "undefined" ? window.location.href : "N/A"
      }\n` +
      `**Timestamp:** ${new Date().toISOString()}\n**Error:** ${message}\n\n` +
      `*Auto-generated by PETadex error handler*`
  )
  return `https://github.com/${GITHUB_REPO}/issues/new?title=${title}&body=${body}&labels=bug`
}

function transformResults(rawResults, queryLength) {
  return (rawResults || []).map((hit, index) => {
    const targetId = hit.target_id || hit.accession
    // Corpus subject ids are pipe-delimited FASTA headers
    // (orf_id|genbank|library|contig|start|end|types); the orf_id is the
    // canonical key for the corpus sequence page.
    const parsed = parseCorpusTargetId(targetId)
    return {
      rank: index + 1,
      accession: targetId,
      target_id: targetId,
      orf_id: hit.orf_id ?? parsed?.orfId ?? null,
      display_id: formatTargetIdLabel(targetId),
      sequence_href: sequenceHrefForTargetId(targetId),
      name: hit.target_name || hit.name || hit.metadata?.definition || null,
      organism: hit.organism || hit.metadata?.organism || null,
      taxonomy: hit.taxonomy || hit.metadata?.taxonomy || null,
      percent_identity: hit.percent_identity ?? hit.identity,
      identity: hit.percent_identity ?? hit.identity,
      evalue: hit.evalue,
      bitscore: hit.bitscore,
      query_coverage:
        queryLength && hit.query_end != null && hit.query_start != null
          ? Math.round(
              ((hit.query_end - hit.query_start + 1) / queryLength) * 100
            )
          : hit.query_coverage ?? null,
      alignment_length: hit.alignment_length,
      query_start: hit.query_start,
      query_end: hit.query_end,
      target_start: hit.target_start,
      target_end: hit.target_end,
      // Full subject protein (DIAMOND full_sseq). Null on hits merged from a
      // part written by a pre-1.3.0 worker.
      target_sequence: hit.target_sequence ?? null,
      enzyme_id: hit.enzyme_id ?? null,
      family: hit.family ?? null,
      component: hit.component ?? null,
      family_pid: hit.family_pid ?? null,
      has_tree: hit.has_tree ?? false,
    }
  })
}

// ─── Loading Screen ────────────────────────────────────────────────────────

const LoadingScreen = ({ sessionId, sequence, elapsed }) => {
  const [stageIdx, setStageIdx] = useState(0)
  const [barPct, setBarPct] = useState(5)
  const [promptIdx, setPromptIdx] = useState(() =>
    Math.floor(Math.random() * LOADING_PROMPTS.length)
  )

  useEffect(() => {
    const interval = setInterval(() => {
      setPromptIdx(i => (i + 1) % LOADING_PROMPTS.length)
    }, 2500)
    return () => clearInterval(interval)
  }, [])

  useEffect(() => {
    // Stage thresholds (s): submit → cache-check → align → enrich.
    // Align dominates (~2 min on the Logan corpus), so give it the widest band.
    const thresholds = [0, 5, 15, 120, 150]
    let next = 0
    for (let i = 0; i < thresholds.length; i++) {
      if (elapsed >= thresholds[i]) next = i
    }
    const clampedStage = Math.min(next, SEARCH_STAGES.length - 2)
    setStageIdx(clampedStage)
    const start = SEARCH_STAGES[clampedStage].pct
    const end =
      SEARCH_STAGES[Math.min(clampedStage + 1, SEARCH_STAGES.length - 1)].pct
    const progress = elapsed - thresholds[clampedStage]
    const span =
      (thresholds[clampedStage + 1] || POLL_TIMEOUT_SECONDS) -
      thresholds[clampedStage]
    setBarPct(
      Math.round(start + (end - start) * Math.min(progress / span, 0.95))
    )
  }, [elapsed])

  const cleanSeq = (sequence || "")
    .replace(/^>.*\n?/gm, "")
    .replace(/[\s\r]/g, "")
    .toUpperCase()

  return (
    <div className="py-10 px-6 flex flex-col items-center gap-6 max-w-lg mx-auto">
      {/* Header */}
      <div className="flex flex-col items-center gap-3 text-center">
        <div className="w-10 h-10 rounded-full border border-t-accent animate-spin" />
        <h2 className="text-xl font-semibold text-primary">
          Searching the enzyme database…
        </h2>
        <p className="text-sm text-secondary-foreground">
          DIAMOND is scanning ~307M sequences in the Logan corpus for similar
          enzymes
        </p>
        <p className="text-xs text-muted-foreground">
          This typically takes 40 seconds on the full corpus.
        </p>
        <p className="text-xs text-muted-foreground font-mono">
          › {LOADING_PROMPTS[promptIdx]}
        </p>
      </div>

      {/* Progress bar */}
      <div className="w-full h-2 bg-surface-sunken rounded-full overflow-hidden">
        <div
          className="h-full bg-accent rounded-full transition-all duration-500"
          style={{ width: `${barPct}%` }}
        />
      </div>

      {/* Stage list */}
      <ul className="w-full space-y-2">
        {SEARCH_STAGES.slice(0, -1).map((stage, i) => {
          const done = i < stageIdx
          const active = i === stageIdx
          return (
            <li key={stage.id} className="flex items-center gap-3">
              <span
                className={[
                  "w-6 h-6 rounded-full flex items-center justify-center text-xs font-bold shrink-0 transition-colors",
                  done
                    ? "bg-success text-white"
                    : active
                    ? "bg-info text-white ring-2 ring-info/30"
                    : "bg-border text-muted-foreground",
                ].join(" ")}
              >
                {done ? "✓" : active ? "…" : ""}
              </span>
              <span
                className={[
                  "text-sm transition-colors",
                  done
                    ? "text-success font-medium"
                    : active
                    ? "text-info font-semibold"
                    : "text-muted-foreground",
                ].join(" ")}
              >
                {stage.label}
              </span>
            </li>
          )
        })}
      </ul>

      {/* Query sequence */}
      {cleanSeq && (
        <div className="w-full bg-surface-sunken border rounded-lg p-3">
          <span className="label block mb-1">
            Query sequence ({cleanSeq.length} aa)
          </span>
          <span className="sequence-display text-2xs">
            {formatSeq(cleanSeq)}
          </span>
        </div>
      )}

      {/* Meta chips */}
      <div className="flex flex-wrap gap-2 justify-center">
        <span className="badge badge-brand">⏱ {elapsed}s elapsed</span>
        {sessionId && (
          <span
            className="badge badge-brand"
            title="Share this ID to reload your results later"
          >
            🔑 {sessionId.slice(0, 12)}…
          </span>
        )}
      </div>
    </div>
  )
}

// ─── Error View ────────────────────────────────────────────────────────────

const ErrorView = ({ error, onNewSearch }) => (
  <div className="py-10 px-6 flex flex-col items-center gap-4 text-center max-w-lg mx-auto">
    <h2 className="text-xl font-semibold text-destructive">Search failed</h2>
    <p className="text-sm text-secondary-foreground">{error.message}</p>
    {error.bugUrl && (
      <a
        href={error.bugUrl}
        target="_blank"
        rel="noopener noreferrer"
        className="text-sm text-accent hover:text-accent-hover underline underline-offset-2"
      >
        🐛 Report this bug on GitHub
      </a>
    )}
    <button className="btn btn-secondary mt-2" onClick={onNewSearch}>
      ← New search
    </button>
  </div>
)

// ─── Main Page ─────────────────────────────────────────────────────────────

const ResultsPage = () => {
  const urlParams =
    typeof window !== "undefined"
      ? new URLSearchParams(window.location.search)
      : new URLSearchParams()

  const sessionId = urlParams.get("job") || null

  const [status, setStatus] = useState(sessionId ? "polling" : "idle")
  const [results, setResults] = useState(null)
  const [metadata, setMetadata] = useState(null)
  const [error, setError] = useState(null)
  const [elapsed, setElapsed] = useState(0)
  const [newSearchCount, setNewSearchCount] = useState(0)
  // How many rows to ask Express for. The server slices the stored result before
  // enriching it, so this bounds a Postgres round trip — it is not just cosmetic.
  const [viewCount, setViewCount] = useState(DEFAULT_RESULT_VIEW)
  const [viewPending, setViewPending] = useState(false)

  const pollRef = useRef(null)
  const timerRef = useRef(null)
  const startTime = useRef(Date.now())

  const searchApiUrl = process.env.GATSBY_SEARCH_API_URL || config.apiUrl

  const stopAll = useCallback(() => {
    if (pollRef.current) clearInterval(pollRef.current)
    if (timerRef.current) clearInterval(timerRef.current)
  }, [])

  const failWithError = useCallback(
    (message, jobId) => {
      stopAll()
      setStatus("error")
      setError({ message, bugUrl: buildBugReportUrl(message, jobId) })
    },
    [stopAll]
  )

  const applyResults = useCallback(data => {
    setResults(
      transformResults(
        data.results,
        data.query_length || data.metadata?.query_length
      )
    )
    setMetadata(
      data.metadata || {
        query_header: data.query_header,
        query_sequence: data.query_sequence,
        query_length: data.query_length,
        num_results: data.num_results,
        database_size: data.database_size,
        search_time_ms: data.search_time_ms,
        timestamp: data.timestamp,
      }
    )
  }, [])

  const handleResults = useCallback(
    (data, sid) => {
      stopAll()
      addJobId(data.job_id || sid)
      applyResults(data)
      setStatus("completed")
      setNewSearchCount(n => n + 1)
    },
    [stopAll, applyResults]
  )

  // Changing the row count re-fetches a deeper slice of the SAME stored result.
  // The sessionId is unchanged, so this is a cache hit by construction — it can
  // never re-run the search. Safe to fire only after completion, which is the
  // only time ResultsView (and therefore the selector) is on screen.
  const handleViewCountChange = useCallback(
    async next => {
      setViewCount(next)
      setViewPending(true)
      try {
        const resp = await fetch(
          `${searchApiUrl}/search/results/${sessionId}?max_results=${next}`
        )
        const data = await resp.json()
        if (resp.ok && data.status === "completed") applyResults(data)
      } catch {
        // Keep the rows already on screen; the selector reverts on next change.
      } finally {
        setViewPending(false)
      }
    },
    [searchApiUrl, sessionId, applyResults]
  )

  const poll = useCallback(
    async sid => {
      try {
        // viewCount is the initial default here: polling stops the moment the
        // result lands, so it can't be stale by the time the user can change it.
        const resp = await fetch(
          `${searchApiUrl}/search/results/${sid}?max_results=${viewCount}`
        )
        const data = await resp.json()
        if (!resp.ok) {
          failWithError(data.error || `Server error ${resp.status}`, sid)
          return
        }
        if (data.status === "completed") handleResults(data, sid)
        else if (data.status === "failed")
          failWithError(data.error || "Search failed", sid)
      } catch {
        failWithError("Failed to fetch results. Please try again.", sid)
      }
    },
    [searchApiUrl, failWithError, handleResults, viewCount]
  )

  useEffect(() => {
    if (!sessionId) return
    startTime.current = Date.now()
    timerRef.current = setInterval(() => {
      const secs = Math.floor((Date.now() - startTime.current) / 1000)
      setElapsed(secs)
      if (secs >= POLL_TIMEOUT_SECONDS) {
        failWithError(
          `Search timed out after ${Math.round(
            POLL_TIMEOUT_SECONDS / 60
          )} minutes. The job may have failed; please try again.`,
          sessionId
        )
      }
    }, 1000)
    poll(sessionId)
    pollRef.current = setInterval(() => poll(sessionId), 3000)
    return () => stopAll()
  }, [sessionId]) // eslint-disable-line react-hooks/exhaustive-deps

  const handleNewSearch = () => {
    stopAll()
    navigate("/search")
  }

  if (!sessionId) {
    if (typeof window !== "undefined") navigate("/search")
    return null
  }

  return (
    <section className="px-4 py-6">
      <Container>
        {/* Breadcrumb */}
        <nav className="flex items-center gap-1.5 text-sm text-secondary mb-4">
          <Link to="/" className="text-accent hover:text-accent-hover">
            PETadex
          </Link>
          <span className="text-border-strong">/</span>
          <span className="text-secondary-foreground">Search results</span>
        </nav>

        {/* Main card */}
        <div className="card">
          {status === "polling" && (
            <LoadingScreen sessionId={sessionId} elapsed={elapsed} />
          )}
          {status === "completed" && results && (
            <ResultsView
              results={results}
              metadata={metadata}
              sessionId={sessionId}
              onNewSearch={handleNewSearch}
              viewCount={viewCount}
              onViewCountChange={handleViewCountChange}
              viewPending={viewPending}
            />
          )}
          {status === "error" && error && (
            <ErrorView error={error} onNewSearch={handleNewSearch} />
          )}
        </div>

        <SearchHistory
          onSelectSearch={sid => window.open(`/results?job=${sid}`, "_blank")}
          currentJobId={status === "completed" ? sessionId : null}
          newSearchCount={newSearchCount}
        />
      </Container>
    </section>
  )
}

export default ResultsPage
